CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ADMINISTRADOR', 'SUPERVISOR', 'RESPONSABLE', 'AUDITOR'))
);

CREATE TABLE expedientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL,
    asunto VARCHAR(255) NOT NULL,
    responsable_id BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_expedientes_codigo UNIQUE (codigo),
    CONSTRAINT fk_expedientes_responsable FOREIGN KEY (responsable_id) REFERENCES usuarios (id),
    CONSTRAINT ck_expedientes_estado CHECK (estado IN ('ABIERTO', 'CERRADO', 'ARCHIVADO'))
);

CREATE TABLE tareas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL,
    titulo VARCHAR(120) NOT NULL,
    titulo_normalizado VARCHAR(120) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    responsable_id BIGINT NOT NULL,
    prioridad VARCHAR(10) NOT NULL,
    fecha_limite DATE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_tareas_expediente FOREIGN KEY (expediente_id) REFERENCES expedientes (id),
    CONSTRAINT fk_tareas_responsable FOREIGN KEY (responsable_id) REFERENCES usuarios (id),
    CONSTRAINT ck_tareas_prioridad CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    CONSTRAINT ck_tareas_estado CHECK (estado IN ('PENDIENTE', 'EN_PROGRESO', 'CERRADA', 'CANCELADA'))
);

CREATE TABLE plazos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    fecha_limite DATE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    motivo_anulacion VARCHAR(250),
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    anulado_en TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_plazos_expediente FOREIGN KEY (expediente_id) REFERENCES expedientes (id),
    CONSTRAINT ck_plazos_estado CHECK (estado IN ('ACTIVO', 'ANULADO'))
);

CREATE TABLE eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(40) NOT NULL,
    recurso VARCHAR(30) NOT NULL,
    recurso_id BIGINT NOT NULL,
    detalle TEXT NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL,
    usuario_id BIGINT,
    CONSTRAINT fk_eventos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX idx_usuarios_rol_activo ON usuarios (rol, activo);
CREATE INDEX idx_expedientes_responsable_estado ON expedientes (responsable_id, estado);
CREATE INDEX idx_expedientes_estado_creado ON expedientes (estado, creado_en);
CREATE INDEX idx_tareas_expediente_estado_titulo ON tareas (expediente_id, estado, titulo_normalizado);
CREATE INDEX idx_tareas_responsable_estado_fecha ON tareas (responsable_id, estado, fecha_limite);
CREATE INDEX idx_tareas_estado_fecha ON tareas (estado, fecha_limite);
CREATE INDEX idx_plazos_expediente_estado ON plazos (expediente_id, estado);
CREATE INDEX idx_plazos_estado_fecha ON plazos (estado, fecha_limite);
CREATE INDEX idx_eventos_fecha ON eventos (fecha);
CREATE INDEX idx_eventos_usuario_fecha ON eventos (usuario_id, fecha);
CREATE INDEX idx_eventos_recurso ON eventos (recurso, recurso_id);
